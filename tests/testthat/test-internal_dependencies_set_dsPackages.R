test_that("internal_dependencies_set_dsPackages messages and returns NULL when no dependencies.R exists", {
  project <- withr::local_tempdir()
  testthat::local_mocked_bindings(here = function(...) file.path(project, ...), .package = "here")
  testthat::expect_message(res <- dsAnalysis:::internal_dependencies_set_dsPackages(add = "dsBase", client = "dsBaseClient"),
                           "No dependencies.R found in the project, so it was not updated.")
  testthat::expect_null(res)
  testthat::expect_false(file.exists(file.path(project, "dependencies.R")))
})

test_that("internal_dependencies_set_dsPackages appends a new block at the end of a dependencies.R without a block and without the bot marker", {
  project <- withr::local_tempdir()
  testthat::local_mocked_bindings(here = function(...) file.path(project, ...), .package = "here")
  writeLines(c("library(here)", "library(dplyr)"), file.path(project, "dependencies.R"))
  res <- dsAnalysis:::internal_dependencies_set_dsPackages(add = "dsBase", client = "dsBaseClient")
  lines <- readLines(file.path(project, "dependencies.R"))
  testthat::expect_identical(lines[1:2], c("library(here)", "library(dplyr)"))
  testthat::expect_identical(lines[3], "")
  testthat::expect_true("library(dsBase); library(dsBaseClient)" %in% lines)
  testthat::expect_identical(lines[length(lines) - 1], "library(dsBase); library(dsBaseClient)")
  testthat::expect_identical(res$server, "dsBase")
  testthat::expect_identical(res$client, "dsBaseClient")
  testthat::expect_identical(nrow(res), 1L)
})

test_that("internal_dependencies_set_dsPackages writes a package without a client as a single library() call", {
  project <- withr::local_tempdir()
