  testthat::expect_true("library(dsSurvival); library(dsSurvivalClient)" %in% lines)
  testthat::expect_identical(nrow(res), 1L)
  testthat::expect_identical(res$server, "dsSurvival")
})

test_that("internal_dependencies_set_dsPackages re-adding a recorded package updates its client without duplicating the entry", {
  project <- withr::local_tempdir()
  testthat::local_mocked_bindings(here = function(...) file.path(project, ...), .package = "here")
  writeLines(c("library(here)"), file.path(project, "dependencies.R"))
  dsAnalysis:::internal_dependencies_set_dsPackages(add = "dsBase", client = "dsBaseClient")
  res <- dsAnalysis:::internal_dependencies_set_dsPackages(add = "dsBase", client = "")
  lines <- readLines(file.path(project, "dependencies.R"))
  testthat::expect_identical(nrow(res), 1L)
  testthat::expect_identical(res$server, "dsBase")
  testthat::expect_identical(res$client, "")
  testthat::expect_true("library(dsBase)" %in% lines)
  testthat::expect_false("library(dsBase); library(dsBaseClient)" %in% lines)
  testthat::expect_length(which(grepl("library(dsBase", lines, fixed = TRUE)), 1L)
})

test_that("internal_dependencies_set_dsPackages adds several packages at once in the order given", {
  project <- withr::local_tempdir()
  testthat::local_mocked_bindings(here = function(...) file.path(project, ...), .package = "here")
  writeLines(c("library(here)"), file.path(project, "dependencies.R"))
  res <- dsAnalysis:::internal_dependencies_set_dsPackages(add = c("dsBase", "dsSurvival"), client = c("dsBaseClient", ""))
  lines <- readLines(file.path(project, "dependencies.R"))
  testthat::expect_identical(res$server, c("dsBase", "dsSurvival"))
  testthat::expect_identical(res$client, c("dsBaseClient", ""))
  first <- which(lines == "library(dsBase); library(dsBaseClient)")
  second <- which(lines == "library(dsSurvival)")
  testthat::expect_length(first, 1L)
  testthat::expect_length(second, 1L)
  testthat::expect_identical(second, first + 1L)
})

test_that("internal_dependencies_set_dsPackages leaves the file round-trippable so a second call reads back the same packages", {
  project <- withr::local_tempdir()
  testthat::local_mocked_bindings(here = function(...) file.path(project, ...), .package = "here")
  writeLines(c("library(here)"), file.path(project, "dependencies.R"))
  written <- dsAnalysis:::internal_dependencies_set_dsPackages(add = c("dsBase", "dsSurvival"), client = c("dsBaseClient", "dsSurvivalClient"))
  recorded <- dsAnalysis:::internal_dependencies_dsPackages(readLines(file.path(project, "dependencies.R")))
  testthat::expect_identical(recorded$server, c("dsBase", "dsSurvival"))
  testthat::expect_identical(recorded$client, c("dsBaseClient", "dsSurvivalClient"))
  testthat::expect_identical(nrow(recorded), nrow(written))
})
