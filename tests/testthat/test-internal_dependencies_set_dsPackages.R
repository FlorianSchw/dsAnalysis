})

test_that("internal_dependencies_set_dsPackages inserts a new block before the bot marker line", {
  project <- withr::local_tempdir()
  testthat::local_mocked_bindings(here = function(...) file.path(project, ...), .package = "here")
  bot_marker <- "#### bot-suggest: packages (updated by datashield-analysis-suggest)"
  writeLines(c("library(here)", bot_marker, "library(somethingElse)"), file.path(project, "dependencies.R"))
  dsAnalysis:::internal_dependencies_set_dsPackages(add = "dsSurvival", client = "dsSurvivalClient")
  lines <- readLines(file.path(project, "dependencies.R"))
  marker_line <- which(lines == bot_marker)
  lib_line <- which(lines == "library(dsSurvival); library(dsSurvivalClient)")
  testthat::expect_length(marker_line, 1L)
  testthat::expect_length(lib_line, 1L)
  testthat::expect_true(lib_line < marker_line)
  testthat::expect_identical(lines[1], "library(here)")
  testthat::expect_identical(lines[length(lines)], "library(somethingElse)")
})

test_that("internal_dependencies_set_dsPackages replaces an existing block in place and keeps the lines around it", {
  project <- withr::local_tempdir()
  testthat::local_mocked_bindings(here = function(...) file.path(project, ...), .package = "here")
  writeLines(c("library(here)"), file.path(project, "dependencies.R"))
  dsAnalysis:::internal_dependencies_set_dsPackages(add = "dsBase", client = "dsBaseClient")
  lines_before <- readLines(file.path(project, "dependencies.R"))
  res <- dsAnalysis:::internal_dependencies_set_dsPackages(add = "dsSurvival", client = "dsSurvivalClient")
  lines <- readLines(file.path(project, "dependencies.R"))
  testthat::expect_identical(lines[1], "library(here)")
  testthat::expect_true("library(dsBase); library(dsBaseClient)" %in% lines)
  testthat::expect_true("library(dsSurvival); library(dsSurvivalClient)" %in% lines)
  testthat::expect_identical(nrow(res), 2L)
  testthat::expect_setequal(res$server, c("dsBase", "dsSurvival"))
  testthat::expect_identical(length(lines), length(lines_before) + 1L)
})

test_that("internal_dependencies_set_dsPackages removes a recorded package from the block and from the returned data frame", {
  project <- withr::local_tempdir()
  testthat::local_mocked_bindings(here = function(...) file.path(project, ...), .package = "here")
  writeLines(c("library(here)"), file.path(project, "dependencies.R"))
  dsAnalysis:::internal_dependencies_set_dsPackages(add = c("dsBase", "dsSurvival"), client = c("dsBaseClient", "dsSurvivalClient"))
